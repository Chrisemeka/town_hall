import * as React from "react"
import { cn } from "@/lib/utils"

const Card = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }>(
  ({ className, interactive, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        "rounded-lg border border-line bg-surface text-ink",
        interactive && "hover:border-accent-ink/40 transition-colors cursor-pointer",
        className
      )}
      {...props}
    />
  )
)
Card.displayName = "Card"

